import { Tier } from "./model";

export interface DropTarget {
  tier: Tier;
  /** Insert before this item; null = end of tier. */
  beforeId: string | null;
}

interface Options {
  onDrop(id: string, target: DropTarget): void;
}

const LONG_PRESS_MS = 220;
const MOUSE_THRESHOLD = 4;
const TOUCH_THRESHOLD = 8;

interface DragState {
  id: string;
  pointerId: number;
  pointerType: string;
  startX: number;
  startY: number;
  started: boolean;
  clone: HTMLElement | null;
  originChip: HTMLElement;
}

/**
 * Pointer-based drag & drop for chips:
 * - mouse: drag starts as soon as the pointer moves a few px
 * - touch: hold the chip for ~220ms to lift it (short moves let the page scroll)
 */
export function attachChipDrag(board: HTMLElement, { onDrop }: Options) {
  let active: DragState | null = null;
  let pressTimer: number | undefined;
  let hoverRow: HTMLElement | null = null;

  const clearHover = () => {
    hoverRow?.classList.remove("drag-over");
    hoverRow = null;
  };

  const findTarget = (x: number, y: number): DropTarget | null => {
    const el = document.elementFromPoint(x, y);
    if (!el) return null;
    const row = el.closest(".tier-row") as HTMLElement | null;
    if (!row || !board.contains(row)) return null;
    const tier = row.dataset.tier as Tier;
    const chipEl = el.closest(".chip") as HTMLElement | null;
    if (!chipEl || !row.contains(chipEl)) return { tier, beforeId: null };
    const chips = Array.from(row.querySelectorAll<HTMLElement>(".chip"));
    const pos = chips.indexOf(chipEl);
    const rect = chipEl.getBoundingClientRect();
    if (x <= rect.left + rect.width / 2) return { tier, beforeId: chipEl.dataset.id ?? null };
    const next = chips[pos + 1];
    return { tier, beforeId: next ? (next.dataset.id ?? null) : null };
  };

  const positionClone = (a: DragState, x: number, y: number) => {
    if (!a.clone) return;
    a.clone.style.left = x - a.clone.offsetWidth / 2 + "px";
    a.clone.style.top = y - a.clone.offsetHeight / 2 + "px";
  };

  const startDrag = (a: DragState, x: number, y: number) => {
    a.started = true;
    const rect = a.originChip.getBoundingClientRect();
    const clone = a.originChip.cloneNode(true) as HTMLElement;
    clone.classList.add("chip-drag-clone");
    clone.style.width = rect.width + "px";
    document.body.appendChild(clone);
    a.clone = clone;
    positionClone(a, x, y);
    a.originChip.classList.add("chip-dragging");
    document.body.classList.add("dragging");
    if (a.pointerType === "touch" && "vibrate" in navigator) navigator.vibrate?.(10);
    window.addEventListener("touchmove", blockScroll, { passive: false });
  };

  const blockScroll = (e: TouchEvent) => {
    if (active?.started) e.preventDefault();
  };

  const onMove = (e: PointerEvent) => {
    const a = active;
    if (!a || e.pointerId !== a.pointerId) return;
    if (!a.started) {
      const dist = Math.hypot(e.clientX - a.startX, e.clientY - a.startY);
      if (a.pointerType === "mouse" && dist > MOUSE_THRESHOLD) {
        startDrag(a, e.clientX, e.clientY);
      } else if (a.pointerType === "touch" && dist > TOUCH_THRESHOLD) {
        endDrag(false); // user is scrolling, not dragging
      }
      return;
    }
    positionClone(a, e.clientX, e.clientY);
    clearHover();
    const el = document.elementFromPoint(e.clientX, e.clientY);
    const row = el?.closest(".tier-row") as HTMLElement | null;
    if (row && board.contains(row)) {
      row.classList.add("drag-over");
      hoverRow = row;
    }
  };

  const endDrag = (drop: boolean, x?: number, y?: number) => {
    const a = active;
    if (!a) return;
    if (pressTimer !== undefined) {
      clearTimeout(pressTimer);
      pressTimer = undefined;
    }
    window.removeEventListener("pointermove", onMove);
    window.removeEventListener("pointerup", onUp);
    window.removeEventListener("pointercancel", onCancel);
    window.removeEventListener("touchmove", blockScroll);
    a.clone?.remove();
    a.originChip.classList.remove("chip-dragging");
    document.body.classList.remove("dragging");
    clearHover();
    active = null;
    if (drop && a.started && x !== undefined && y !== undefined) {
      const target = findTarget(x, y);
      if (target && target.beforeId !== a.id) onDrop(a.id, target);
      // swallow the click generated by releasing the pointer after a drag
      const swallow = (e: Event) => {
        e.preventDefault();
        e.stopPropagation();
      };
      window.addEventListener("click", swallow, { capture: true, once: true });
    }
  };

  const onUp = (e: PointerEvent) => {
    if (active && e.pointerId === active.pointerId) endDrag(true, e.clientX, e.clientY);
  };

  const onCancel = (e: PointerEvent) => {
    if (active && e.pointerId === active.pointerId) endDrag(false);
  };

  board.addEventListener("pointerdown", (e) => {
    if (active) return;
    if (e.pointerType === "mouse" && e.button !== 0) return;
    const t = e.target as HTMLElement;
    const chip = t.closest(".chip") as HTMLElement | null;
    if (!chip || !board.contains(chip) || t.closest(".chip-x")) return;
    active = {
      id: chip.dataset.id ?? "",
      pointerId: e.pointerId,
      pointerType: e.pointerType,
      startX: e.clientX,
      startY: e.clientY,
      started: false,
      clone: null,
      originChip: chip,
    };
    window.addEventListener("pointermove", onMove);
    window.addEventListener("pointerup", onUp);
    window.addEventListener("pointercancel", onCancel);
    if (e.pointerType === "touch") {
      pressTimer = window.setTimeout(() => {
        if (active && !active.started) startDrag(active, e.clientX, e.clientY);
      }, LONG_PRESS_MS);
    }
  });

  board.addEventListener("contextmenu", (e) => {
    if (active) e.preventDefault();
  });
}
